#!/usr/bin/env python3
"""Generate the Kubernetes base manifests from docker-compose.yml.

Why generate rather than hand-write
-----------------------------------
The hand-written base listed three services. The platform has thirty. The CD
pipeline applied `k8s/base/*.yaml`, saw no error, waited for a rollout of the
three deployments that did exist, and reported a successful deploy — for
twenty-seven services that were never deployed at all. Nothing in the pipeline
could have told anyone: a manifest that is absent produces no error, and
`kubectl rollout status` on a label selector that matches three deployments
exits zero.

docker-compose.yml is the one description of every service that is kept
current, because it is the file people actually run. Deriving the manifests
from it means a new service is deployable the moment it is runnable locally,
and `--check` in CI fails the build when the two drift apart.

Usage
-----
    scripts/k8s-manifests.py            # rewrite the generated files
    scripts/k8s-manifests.py --check    # fail if they are out of date
"""

