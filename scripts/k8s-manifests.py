def render_realtime() -> str:
    """The real-time transport: /ws and /events.

    Written out rather than run through the service template, because the one
    assumption that template makes about every service is the one thing this
    binary cannot do: scale out.

    The hub, the presence registry and the collaborative-inspection sessions are
    all in process memory, and no backplane joins two copies of them. At two
    replicas a field's watchers are split across pods and each half sees only
    its own half's events; two people editing the same inspection get two
    sessions that silently diverge and the last writer wins. So: one replica, no
    autoscaler, and Recreate rather than RollingUpdate — a rolling deploy runs
    the new pod alongside the old one, which is the split-room state again for
    as long as the rollout takes. Clients reconnect, which they must handle
    anyway; a tractor drives out of signal several times a day.

    Nothing about that is permanent. A Redis or Kafka fan-out behind the hub
    would make this horizontally scalable, and then it belongs in the template
    like everything else.
    """
    return """---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: realtime
  namespace: yieldpoint
  labels:
    app.kubernetes.io/name: realtime
    app.kubernetes.io/part-of: yieldpoint
spec:
  replicas: 1
  selector:
    matchLabels:
      app.kubernetes.io/name: realtime
  strategy:
    # See render_realtime(): two live pods split every room, so the old one goes
    # before the new one arrives.
    type: Recreate
  template:
    metadata:
      labels:
        app.kubernetes.io/name: realtime
        app.kubernetes.io/part-of: yieldpoint
    spec:
      securityContext:
        runAsNonRoot: true
        runAsUser: 65532
        seccompProfile:
          type: RuntimeDefault
      # Longer than the 30s shutdown in cmd/realtime/main.go. At the default of
      # 30s the kubelet's SIGKILL lands exactly as the server gives up on its
      # own deadline, so a drain would cut open WebSockets mid-frame every time.
      terminationGracePeriodSeconds: 45
      containers:
        - name: realtime
          image: ghcr.io/ppusapati/yieldpoint/realtime:latest
          ports:
            - containerPort: 8080
              name: http
          envFrom:
            - configMapRef:
                name: yieldpoint-config
          env:
            - name: JWT_SECRET
              valueFrom:
                secretKeyRef:
                  name: yieldpoint-secrets
                  key: JWT_SECRET
            - name: PORT
              value: "8080"
          resources:
            requests:
              memory: "128Mi"
              cpu: "100m"
            limits:
              # Memory is the dimension that matters: one entry per open
              # connection, per room member and per live inspection session.
              memory: "512Mi"
              cpu: "500m"
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities:
              drop: ["ALL"]
          readinessProbe:
            httpGet:
              path: /ready
              port: http
            initialDelaySeconds: 3
            periodSeconds: 5
          livenessProbe:
            httpGet:
              path: /health
              port: http
            initialDelaySeconds: 10
            periodSeconds: 20
---
apiVersion: v1
kind: Service
metadata:
  name: realtime
  namespace: yieldpoint
  labels:
    app.kubernetes.io/name: realtime
    app.kubernetes.io/part-of: yieldpoint
spec:
  selector:
    app.kubernetes.io/name: realtime
  ports:
    - name: http
      port: 8080
      targetPort: http
---
apiVersion: policy/v1
kind: PodDisruptionBudget
metadata:
  name: realtime
  namespace: yieldpoint
spec:
  # A single replica, so this cannot protect availability — it can only refuse
  # to let a node drain, for ever. It is written as "one may go" deliberately:
  # the transport is reconnectable and a stuck drain is worse than a reconnect.
  maxUnavailable: 1
  selector:
    matchLabels:
      app.kubernetes.io/name: realtime
"""



def service_database(name: str, spec: dict) -> tuple[str, str] | None:
    """The (host, database) a service connects to, read out of its compose DSN."""
    env = spec.get("environment") or {}
    dsn = env.get("DATABASE_URL")
    if not isinstance(dsn, str):
        return None
    # The value is ${FOO_DATABASE_URL:-postgres://user:${PW:?...}@postgres:5432/foo_service?...}.
    # Anchored on the host and port rather than on "postgres://", because the
    # credentials in between contain a nested ${...} whose braces and spaces
    # end a naive character class early — which silently yielded one database
    # out of twenty-nine when the DSNs moved off the superuser.
    match = re.search(r"@([A-Za-z0-9_-]+):\d+/([A-Za-z0-9_]+)", dsn)
    return match.groups() if match else None


def render_initdb(services: dict[str, dict], host: str, purpose: str) -> str:
    """The cluster bootstrap script docker-compose mounts into postgres.

    Generated because the hand-written one had gone seven databases stale:
    advisory, device, finance, market, planning, soil-lab and sustainability
    all had migrations and no database to apply them to, so those containers
    could not start at all. A list of services maintained by hand goes out of
    date the moment somebody adds a service, and nothing says so.
    """
    databases = sorted(
        {
            target[1]
            for name, spec in services.items()
            if (target := service_database(name, spec)) and target[0] == host
        }
    )
    listing = "\n".join(f"  {db}" for db in databases)
    return f"""#!/usr/bin/env bash
# Generated by scripts/k8s-manifests.py from docker-compose.yml. Do not edit.
#
# Creates the roles services connect with, and one database per service, inside
# {purpose}. Mounted as a docker-entrypoint-initdb.d
# script by docker-compose, so it runs once on an empty cluster.
#
# Three roles, because one would defeat row-level security:
#
#   yp_migrator  owns the schema and is the only role that runs DDL. Services
#                migrate as this at boot and then drop it.
#   yp_app       DML only, and NOT a superuser, so the RLS policies apply to
#                it. This is what the request path connects as.
#   yp_system    DML with BYPASSRLS, for the two things that legitimately read
#                across tenants: alert-service's rule scanner and
#                irrigation-service's run-closing sweep. A scoped role would
#                leave both reading nothing, silently.
#
# Compose used to run every service as the superuser, which bypasses RLS
# entirely — so the policies had never run anywhere, in development or in CI.
set -euo pipefail

DATABASES=(
{listing}
)

psql -v ON_ERROR_STOP=1 \
  -v migrator_pw="${{DB_MIGRATOR_PASSWORD}}" \
  -v app_pw="${{DB_APP_PASSWORD}}" \
  -v system_pw="${{DB_SYSTEM_PASSWORD}}" \
  --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'SQL'
-- \gexec rather than a DO block: psql does not substitute :'variables'
-- inside dollar-quoted strings, so a password would be sent literally as
-- ":'app_pw'".
SELECT format('CREATE ROLE yp_migrator LOGIN PASSWORD %L', :'migrator_pw')
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'yp_migrator')\gexec

SELECT format('CREATE ROLE yp_app LOGIN PASSWORD %L', :'app_pw')
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'yp_app')\gexec

-- BYPASSRLS, and only this role has it.
SELECT format('CREATE ROLE yp_system LOGIN BYPASSRLS PASSWORD %L', :'system_pw')
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'yp_system')\gexec
SQL

for db in "${{DATABASES[@]}}"; do
  echo "Creating database: $db"
  psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-SQL
    SELECT 'CREATE DATABASE $db OWNER yp_migrator'
    WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '$db')\gexec
SQL

  # Grants inside the database. The default privileges matter more than the
  # explicit ones: migrations have not run yet, so every table a service uses
  # is created after this, by yp_migrator, and would otherwise be readable by
  # nobody but its owner.
  psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$db" <<-SQL
    GRANT ALL ON SCHEMA public TO yp_migrator;
    GRANT USAGE ON SCHEMA public TO yp_app, yp_system;

    ALTER DEFAULT PRIVILEGES FOR ROLE yp_migrator IN SCHEMA public
      GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO yp_app, yp_system;
    ALTER DEFAULT PRIVILEGES FOR ROLE yp_migrator IN SCHEMA public
      GRANT USAGE, SELECT ON SEQUENCES TO yp_app, yp_system;
SQL
done

echo "Created ${{#DATABASES[@]}} databases and the yp_migrator/yp_app/yp_system roles."
"""


def render_services(services: dict[str, dict]) -> str:
    parts = [BANNER]
    for name, spec in services.items():
        parts.append(render_service(name, spec))
    # realtime serves /ws and /events and is built from the shared Dockerfile
    # with CMD_PATH rather than SERVICE, so it is not in load_services() either.
    # It had no Kubernetes manifest at all until now, and neither did the
    # monolith it replaces — which means the real-time features have never run
    # in a cluster, only under compose.
    parts.append(render_realtime())
    # The two gateways are not Go microservices and are not built from the
    # shared Dockerfile, so compose does not describe them with a SERVICE arg.
    # They are still deployed, and leaving them out of the generated base would
    # reintroduce exactly the hole this script exists to close.
    parts.append(render_ai_gateway())
    parts.append(render_api_gateway())
    return "".join(parts)


def render_secrets(services: dict[str, dict]) -> str:
    keys = []
    for name, spec in services.items():
        env = spec.get("environment") or {}
        if "DATABASE_URL" in env:
            keys.append(database_key(name))

    rows = "".join(f'  {key}: ""\n' for key in sorted(keys))
    return f"""{BANNER}#
# The values are empty on purpose. They are filled by the cluster's secret
# manager — sealed-secrets, External Secrets or the CD pipeline — and a real
# connection string committed here would be a credential in git history that
# rotating the database does not remove.
apiVersion: v1
kind: Secret
metadata:
  name: yieldpoint-secrets
  namespace: yieldpoint
type: Opaque
stringData:
  POSTGRES_PASSWORD: ""
  POSTGRES_REPLICATION_PASSWORD: ""
  JWT_SECRET: ""
  S3_ACCESS_KEY_ID: ""
  S3_SECRET_ACCESS_KEY: ""
  EXTERNAL_API_KEY: ""
  GRAFANA_ADMIN_PASSWORD: ""
---
apiVersion: v1
kind: Secret
metadata:
  name: database-urls
  namespace: yieldpoint
type: Opaque
stringData:
{rows}"""


def workflow_matrix(path: Path) -> set[str]:
    """The service names in a workflow's build matrix."""
    text = path.read_text()
    names: set[str] = set()
    for match in re.finditer(r"^\s+service:\s*$", text, re.M):
        for line in text[match.end():].splitlines()[1:]:
            entry = re.match(r"^\s+- ([a-z0-9-]+)\s*$", line)
            if not entry:
                break
            names.add(entry.group(1))
    return names


def helm_services() -> set[str]:
    values = yaml.safe_load(HELM_VALUES.read_text())
    return {f"{key}-service" for key in (values.get("services") or {})}


def check_consumers(services: dict[str, dict]) -> list[str]:
    """Every place that keeps its own copy of the service list must agree."""
    expected = set(services)
    problems = []

    for label, actual in [
        ("the CI build matrix (.github/workflows/ci.yml)", workflow_matrix(CI_WORKFLOW)),
        ("the CD build matrix (.github/workflows/cd.yml)", workflow_matrix(CD_WORKFLOW)),
        ("the Helm chart's services (k8s/helm/yieldpoint/values.yaml)", helm_services()),
    ]:
        missing = sorted(expected - actual)
        extra = sorted(actual - expected)
        if missing:
            problems.append(f"{label} is missing: {', '.join(missing)}")
        if extra:
            problems.append(f"{label} lists services compose does not build: {', '.join(extra)}")

    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if the generated files are stale",
    )
    args = parser.parse_args()

    services = load_services()
    if not services:
        print("error: no services found in docker-compose.yml", file=sys.stderr)
        return 1

    outputs = {
        SERVICES_OUT: render_services(services),
        SECRETS_OUT: render_secrets(services),
        INITDB_OUT: render_initdb(
            services, "postgres", "the shared PostgreSQL instance"
        ),
        INITVEC_OUT: render_initdb(
            services,
            "pgvector",
            "the pgvector instance, which advisory-service uses for its "
            "retrieval embeddings",
        ),
    }

    problems = check_consumers(services)

    if args.check:
        for path, content in outputs.items():
            existing = path.read_text() if path.exists() else ""
            if existing != content:
                problems.append(
                    f"{path.relative_to(ROOT)} is out of date — run scripts/k8s-manifests.py"
                )
        if problems:
            print(
                f"\n{len(problems)} problem(s). The deployed manifests and the service "
                f"list have drifted apart, which is how a service ends up built by CI, "
                f"pushed by CD, and never deployed:\n",
                file=sys.stderr,
            )
            for problem in problems:
                print(f"  - {problem}", file=sys.stderr)
            return 1
        print(f"ok: {len(services)} services, manifests up to date")
        return 0

    for path, content in outputs.items():
        path.write_text(content)
        if path.suffix == ".sh":
            path.chmod(0o755)
        print(f"wrote {path.relative_to(ROOT)}")

    if problems:
        print("\nStill out of step (these are hand-maintained):", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1

    print(f"ok: {len(services)} services")
    return 0


if __name__ == "__main__":
    sys.exit(main())
