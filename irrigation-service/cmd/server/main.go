// Package main wires all irrigation-service layers together and starts the HTTP server.
// Pre-requisites: run `buf generate` in irrigation-service/ to produce api/v1/*.pb.go
package main

import (
	"context"
	"encoding/json"
	"fmt"
	"log"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	"connectrpc.com/connect"
	"github.com/IBM/sarama"
	"github.com/jackc/pgx/v5/pgxpool"
	"go.uber.org/zap"

	"p9e.in/samavaya/packages/authz"
	"p9e.in/samavaya/packages/connect/interceptors"
	connectserver "p9e.in/samavaya/packages/connect/server"
	"p9e.in/samavaya/packages/database/migrate"
	kafkaconfig "p9e.in/samavaya/packages/events/config"
	kafkaconsumer "p9e.in/samavaya/packages/events/consumer"
	"p9e.in/samavaya/packages/events/domain"
	"p9e.in/samavaya/packages/middleware"
	"p9e.in/samavaya/packages/outbox"
	"p9e.in/samavaya/packages/p9log"

	// Generated by buf generate — run `buf generate` in irrigation-service/ first.
	irrigationv1connect "p9e.in/samavaya/agriculture/irrigation-service/api/v1/irrigationv1connect"

	// Inbound adapters
	eventsadapter "p9e.in/samavaya/agriculture/irrigation-service/internal/adapters/inbound/events"
	grpcadapter "p9e.in/samavaya/agriculture/irrigation-service/internal/adapters/inbound/grpc"

	// Outbound adapters
	aiadapter "p9e.in/samavaya/agriculture/irrigation-service/internal/adapters/outbound/ai"
	clientsadapter "p9e.in/samavaya/agriculture/irrigation-service/internal/adapters/outbound/clients"
	controlleradapter "p9e.in/samavaya/agriculture/irrigation-service/internal/adapters/outbound/controller"
	kafkaadapter "p9e.in/samavaya/agriculture/irrigation-service/internal/adapters/outbound/kafka"
	postgresadapter "p9e.in/samavaya/agriculture/irrigation-service/internal/adapters/outbound/postgres"

	// Application core
	"p9e.in/samavaya/agriculture/irrigation-service/internal/application"
	// Aliased: `domain` above is the shared event vocabulary, not this
	// service's.
	irrigationdomain "p9e.in/samavaya/agriculture/irrigation-service/internal/domain"
	"p9e.in/samavaya/agriculture/irrigation-service/internal/ports/inbound"
	"p9e.in/samavaya/agriculture/irrigation-service/internal/ports/outbound"
	connectclient "p9e.in/samavaya/packages/connect/client"
)

func main() {
	zapLogger, err := zap.NewProduction()
	if err != nil {
		log.Fatalf("failed to create logger: %v", err)
	}
	defer zapLogger.Sync() //nolint:errcheck
	logger := p9log.NewLogger(zapLogger)

	// ── JWT ─────────────────────────────────────────────────────────────────
	if err := authz.InitJWTFromEnv(); err != nil {
		log.Fatalf("JWT not configured: %v — refusing to start without authentication", err)
	}
	jwtValidator := interceptors.NewAuthzJWTValidator()

	dsn := envOr("DATABASE_URL", "postgres://localhost:5432/irrigation_service?sslmode=disable")
	kafkaBroker := os.Getenv("KAFKA_BROKER") // optional; events are best-effort
	port := envOr("PORT", "8080")
	fieldServiceURL := envOr("FIELD_SERVICE_URL", "http://localhost:8082")
	farmServiceURL := envOr("FARM_SERVICE_URL", "http://localhost:8081")

	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()

	pool, err := pgxpool.New(ctx, dsn)
	if err != nil {
		log.Fatalf("failed to connect to database: %v", err)
	}
	defer pool.Close()

	if err := pool.Ping(ctx); err != nil {
		log.Fatalf("database ping failed: %v", err)
	}

	// ── Auto-migrate ─────────────────────────────────────────────────────
	migrateCtx, migrateCancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer migrateCancel()
	if err := migrate.Up(migrateCtx, pool, os.DirFS(envOr("MIGRATIONS_DIR", "migrations")), zapLogger); err != nil {
		log.Fatalf("migration failed: %v", err)
	}

	// ── Kafka producer (optional) ────────────────────────────────────────────
	var kafkaProducer sarama.SyncProducer
	if kafkaBroker != "" {
		cfg := sarama.NewConfig()
		cfg.Producer.Return.Successes = true
		kafkaProducer, err = sarama.NewSyncProducer([]string{kafkaBroker}, cfg)
		if err != nil {
			log.Printf("WARNING: failed to create Kafka producer: %v — events will be dropped", err)
		} else {
			defer kafkaProducer.Close()
		}
	}

	// ── Outbound adapters ────────────────────────────────────────────────────
	repo := postgresadapter.NewIrrigationRepository(pool, logger)
	outboxPub := outbox.NewPublisher(pool, zapLogger)
	kafkaPub := kafkaadapter.NewEventPublisher(kafkaProducer, logger)

	fieldClient := clientsadapter.NewFieldClient(fieldServiceURL, connectclient.NewHTTPClient(connectclient.DefaultConfig(fieldServiceURL)), connect.WithInterceptors(connectclient.ContextPropagator()))
	farmClient := clientsadapter.NewFarmClient(farmServiceURL, connectclient.NewHTTPClient(connectclient.DefaultConfig(farmServiceURL)), connect.WithInterceptors(connectclient.ContextPropagator()))

	// ── Application service (core) ───────────────────────────────────────────
	svc := application.NewIrrigationService(repo, outboxPub, fieldClient, farmClient, pool, logger)

	// ET0-driven scheduling needs both weather-service and the AI gateway;
	// without either, decisions fall back to the soil-moisture heuristic.
	weatherServiceURL := envOr("WEATHER_SERVICE_URL", "")
	aiGatewayURL := envOr("AI_GATEWAY_URL", "")
	if weatherServiceURL != "" && aiGatewayURL != "" {
		weatherClient := clientsadapter.NewWeatherClient(weatherServiceURL,
			connectclient.NewHTTPClient(connectclient.DefaultConfig(weatherServiceURL)),
			connect.WithInterceptors(connectclient.ContextPropagator()))
		waterClient, err := aiadapter.NewWaterBalanceClient(aiGatewayURL, p9log.NewHelper(logger))
		if err != nil {
			log.Printf("WARNING: AI gateway unavailable, irrigation decisions use heuristic: %v", err)
		} else {
			defer waterClient.Close() //nolint:errcheck
			svc.WithWaterBalance(weatherClient, waterClient)
		}
	} else {
		log.Printf("water-balance scheduling disabled (set WEATHER_SERVICE_URL and AI_GATEWAY_URL to enable)")
	}

	// ── Actuation ────────────────────────────────────────────────────────────
	//
	// The part that acts on a real farm. Everything above produces advice;
	// this opens a valve, so a deployment with nothing configured here refuses
	// to start irrigation rather than recording runs it did not perform.
	clients := map[irrigationdomain.Protocol]outbound.ControllerClient{}

	if broker := envOr("MQTT_BROKER_URL", ""); broker != "" {
		client, err := controlleradapter.NewMQTTClient(controlleradapter.MQTTConfig{
			BrokerURL: broker,
			ClientID:  envOr("MQTT_CLIENT_ID", "irrigation-service"),
			Username:  os.Getenv("MQTT_USERNAME"),
			Password:  os.Getenv("MQTT_PASSWORD"),
		}, logger)
		if err != nil {
			log.Printf("WARNING: MQTT controller client not configured: %v", err)
		} else {
			clients[irrigationdomain.ProtocolMQTT] = client
		}
	}

	if ns := envOr("LORAWAN_SERVER_URL", ""); ns != "" {
		client, err := controlleradapter.NewLoRaWANClient(controlleradapter.LoRaWANConfig{
			BaseURL:  ns,
			APIToken: os.Getenv("LORAWAN_API_TOKEN"),
			// Confirmed downlinks cost airtime and a retransmission budget.
			// For a command that opens a valve that is the right trade: the
			// alternative is not knowing whether a stop was heard.
			Confirmed: true,
		})
		if err != nil {
			log.Printf("WARNING: LoRaWAN controller client not configured: %v", err)
		} else {
			clients[irrigationdomain.ProtocolLoRaWAN] = client
		}
	}

	// Modbus needs no shared configuration: the panel's address is the
	// controller's own endpoint, so it is enabled unless explicitly turned off.
	if envOr("MODBUS_ENABLED", "true") == "true" {
		clients[irrigationdomain.ProtocolModbus] = controlleradapter.NewModbusClient(controlleradapter.DefaultTimeout)
	}

	if len(clients) == 0 {
		// Warned loudly rather than defaulted, because the symptom is a
		// TriggerIrrigation that refuses every request and an operator with no
		// reason to connect that to a missing environment variable.
		log.Printf("WARNING: no controller clients configured; TriggerIrrigation and StopIrrigation " +
			"will refuse every request. Set MQTT_BROKER_URL, LORAWAN_SERVER_URL, or leave MODBUS_ENABLED on.")
	} else {
		registry := controlleradapter.NewRegistry(clients)
		// A narrow store rather than the whole repository: the component that
		// opens valves does not get the ability to rewrite schedules.
		actuationStore := postgresadapter.NewActuationStore(pool, logger)
		svc.WithActuator(application.NewActuator(actuationStore, registry, actuationStore, kafkaPub, logger))
		log.Printf("actuation enabled for protocols: %v", registry.Protocols())
	}

	// ── Inbound adapters ─────────────────────────────────────────────────────
	handler := grpcadapter.NewIrrigationHandler(svc, logger)

	mwCfg := connectserver.MiddlewareConfig{
		EnableRecovery:  true,
		EnableRequestID: true,
		EnableLogging:   true,
		EnableDB:        true,
		DBPool:          pool,
		EnableAuth:      true,
		JWTValidator:    jwtValidator,
		EnableAuthz:     true,
		EnableRLS:       true,
		RLSLevel:        interceptors.ScopeLevelTenant,
	}
	connectOpt := connectserver.NewConnectOption(mwCfg)

	mux := http.NewServeMux()
	const serviceName = "irrigation-service"
	path, irrigationHandler := irrigationv1connect.NewIrrigationServiceHandler(handler,
		connect.WithInterceptors(
			middleware.MetricsInterceptor(serviceName),
			middleware.TracingInterceptor(serviceName),
		),
		connectOpt,
	)
	mux.Handle(path, irrigationHandler)

	mux.HandleFunc("/health", func(w http.ResponseWriter, _ *http.Request) {
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write([]byte(`{"status":"ok"}`))
	})
	mux.HandleFunc("/ready", func(w http.ResponseWriter, _ *http.Request) {
		if err := pool.Ping(context.Background()); err != nil {
			w.WriteHeader(http.StatusServiceUnavailable)
			return
		}
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write([]byte(`{"status":"ready"}`))
	})

	serverCfg := connectserver.DefaultServerConfig(port)
	wrapped := connectserver.WrapAll(mux, serverCfg)
	srv := connectserver.NewHTTPServer(serverCfg, wrapped)

	// ── Outbox relay (background) ────────────────────────────────────────
	relayCtx, relayCancel := context.WithCancel(context.Background())
	defer relayCancel()
	relay := outbox.NewRelay(pool, kafkaPub, zapLogger)
	go relay.Run(relayCtx)

	// ── Kafka event consumer (background) ────────────────────────────────
	if kafkaBroker != "" {
		eventConsumer := eventsadapter.NewIrrigationConsumer(svc, logger)
		kc := kafkaconsumer.NewKafkaConsumer(&kafkaconfig.KafkaConfig{
			Broker:       kafkaBroker,
			Group:        "irrigation-service",
			KafkaVersion: "3.5.0",
			Assignor:     "sticky",
		}, logger)
		consumerCtx, consumerCancel := context.WithCancel(context.Background())
		defer consumerCancel()
		for _, topic := range eventConsumer.Topics() {
			if err := kc.Subscribe(consumerCtx, topic, func(ctx context.Context, data []byte) error {
				var event domain.DomainEvent
				if err := json.Unmarshal(data, &event); err != nil {
					return fmt.Errorf("unmarshal domain event: %w", err)
				}
				return eventConsumer.HandleEvent(ctx, &event)
			}); err != nil {
				log.Printf("WARNING: failed to subscribe to %s: %v", topic, err)
			}
		}
	}

	// ── Closing finished runs ────────────────────────────────────────────────
	//
	// A start command carries a duration the controller enforces locally, so
	// the valve shuts on its own and nothing tells this service. Without this
	// sweep those runs stay ACTIVE for ever and are never metered — and every
	// sensor-driven run ends that way, because nobody is present to stop one.
	//
	// Set RUN_CLOSE_INTERVAL to 0 to turn it off; off means water usage is
	// recorded only for runs an operator stopped by hand.
	sweepCtx, sweepCancel := context.WithCancel(context.Background())
	defer sweepCancel()
	if interval := envDuration("RUN_CLOSE_INTERVAL", time.Minute); interval > 0 {
		go closeFinishedRuns(sweepCtx, svc, interval, p9log.NewHelper(logger))
	} else {
		log.Printf("run closing disabled; water usage will only be recorded for runs stopped by hand")
	}

	quit := make(chan os.Signal, 1)
	signal.Notify(quit, syscall.SIGINT, syscall.SIGTERM)

	go func() {
		p9log.NewHelper(logger).Infow("msg", "irrigation-service starting", "port", port)
		if err := srv.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			log.Fatalf("server error: %v", err)
		}
	}()

	<-quit
	p9log.NewHelper(logger).Infow("msg", "shutting down irrigation-service")
	sweepCancel()

	shutCtx, shutCancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer shutCancel()
	if err := srv.Shutdown(shutCtx); err != nil {
		log.Printf("graceful shutdown error: %v", err)
	}
}

func envOr(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

// closeFinishedRuns sweeps for runs whose water has stopped, on a ticker.
//
// runCloseBatch bounds one pass so a backlog — a service that was down for an
// afternoon — is worked through over several ticks rather than in one
// transaction that holds a connection while it reads a meter per run.
const runCloseBatch = 100

func closeFinishedRuns(ctx context.Context, svc inbound.IrrigationService, every time.Duration, log *p9log.Helper) {
	ticker := time.NewTicker(every)
	defer ticker.Stop()

	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
			if _, err := svc.CloseFinishedRuns(ctx, runCloseBatch); err != nil {
				// Logged and retried on the next tick. A database blip must
				// not stop runs being closed for the rest of the process's
				// life.
				log.Warnw("msg", "could not close finished runs", "error", err)
			}
		}
	}
}

// envDuration reads a duration, falling back when it is unset or unreadable.
func envDuration(key string, fallback time.Duration) time.Duration {
	raw := os.Getenv(key)
	if raw == "" {
		return fallback
	}
	d, err := time.ParseDuration(raw)
	if err != nil {
		log.Printf("WARNING: %s=%q is not a duration; using %s", key, raw, fallback)
		return fallback
	}
	return d
}
